/**
 * Status window of the network server of the simulator, which is opened by
 * RbmkSimulator as soon as the server is started from the menu of a
 * ControlPanel. It is a view of its own and does not belong to any ControlPanel,
 * because the server and the simulation keep running when all control panels
 * are closed, so that the connected network clients keep working. This window
 * therefore becomes the main window of a server session: closing it shuts down
 * the whole application.
 * <p>
 * The window displays whether the server socket listens, its port, the state
 * of the simulation, how often the simulation was restarted and which clients
 * are connected. It polls this state once per second with a Swing timer from
 * RbmkSimulator instead of receiving MVC updates, because the state belongs to
 * the application and not to the model, which can be replaced by a restart.
 * The restart button lets RbmkSimulator create a completely new MainLoop, which
 * is meant for the case that the simulation crashed, while the controller and
 * all network connections stay open.
 * <p>
 * In addition, the window is an MVC view of its own, which RbmkSimulator
 * registers with an AwtUpdater at the controller. From the updates it only
 * evaluates the output snapshot of the model, from which it displays the
 * minimum, average and maximum cycle time that CycleTimeStatistics of the
 * MainLoop adds to the output values.
 * <p>
 * LLM code generated with Claude Opus 5.5
 *
 * @author Viktor Alexander Hartung
 */
