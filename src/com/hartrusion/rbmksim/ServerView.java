    private void jButtonRestartActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonRestartActionPerformed
        int answer = JOptionPane.showConfirmDialog(this,
                "The simulation will be replaced by a new simulation in its "
                + "initial state.\nConnected clients stay connected. Continue?",
                "Restart Simulation", JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE);
        if (answer != JOptionPane.YES_OPTION) {
            return;
        }
        jButtonRestart.setEnabled(false);
        // The restart waits for the old simulation thread to stop, which must
        // not block the event dispatch thread.
        Thread restartThread = new Thread(() -> {
            try {
                application.restartMainLoop();
            } catch (RuntimeException e) {
                logger.log(java.util.logging.Level.SEVERE,
                        "Restart of the simulation failed.", e);
            } finally {
                java.awt.EventQueue.invokeLater(() -> {
                    jButtonRestart.setEnabled(true);
                    updateStatus();
                });
            }
        }, "MainLoop-Restart");
        restartThread.start();
    }//GEN-LAST:event_jButtonRestartActionPerformed

