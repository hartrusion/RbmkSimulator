    /**
     * Asks the user whether the server and the simulation shall be terminated,
     * and terminates the application on confirmation. This disconnects all
     * network clients and closes all control panels.
     */
    private void confirmShutdown() {
        int answer = JOptionPane.showConfirmDialog(this,
                "Shut down the server and the simulation?\n"
                + "All clients will be disconnected.",
                "Shut Down Server", JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE);
        if (answer == JOptionPane.YES_OPTION) {
            System.exit(0);
        }
    }

    /**
     * Refreshes all displayed values with the current state of the server and
     * the simulation. Called once per second by the status timer and after a
     * restart.
     */
    private void updateStatus() {
        com.hartrusion.mvc.net.SocketServer server
                = application.getSocketServer();
        String serverFailure = application.getServerFailure();
        if (serverFailure != null) {
            jLabelServer.setText("Failed: " + serverFailure);
        } else if (server != null && server.isListening()) {
            jLabelServer.setText("Listening");
        } else {
            jLabelServer.setText("Starting...");
        }
        jLabelPort.setText(Integer.toString(application.getServerPort()));

        jLabelSimulation.setText(getSimulationStatusText());
        jLabelRestarts.setText(
                Integer.toString(application.getRestartCount()));

        List<String> clients = List.of();
        if (server != null) {
            clients = server.getConnectedClients();
        }
        jLabelClientCount.setText(Integer.toString(clients.size()));
        String clientText = String.join("\n", clients);
        // Only set when changed, so that a selection in the text area is not
        // lost every second.
        if (!clientText.equals(jTextAreaClients.getText())) {
            jTextAreaClients.setText(clientText);
        }
    }

    /**
     * @return text that describes the state of the current MainLoop
     */
    private String getSimulationStatusText() {
        if (application.isRestarting()) {
            return "Restarting...";
        }
        MainLoop mainLoop = application.getMainLoop();
        if (mainLoop == null) {
            return "Not running";
        }
        if (mainLoop.isCrashed()) {
            return "Crashed (restart required)";
        }
        if (mainLoop.isPaused()) {
            return "Paused";
        }
        return "Running";
    }

